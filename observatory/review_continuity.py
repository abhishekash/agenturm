DRAFT_FORMAT='agenturm-continuity-draft-v1'
SCOPE_FIELDS=('receiver','producer','agent_id','session_id','run_id','turn_id','kind','run_start_ns','run_end_ns')


def source_scope(projection):
    if not isinstance(projection,dict) or projection.get('format')!='agenturm-review-v1':
        raise TaskError('Choose a frozen Agenturm Review projection.')
    _link(projection)  # Reuse existing strict run/turn and usage consistency checks.
    scope=projection.get('scope') or {}
    if not scope.get('receiver') or not scope.get('producer') or not (scope.get('agent_id') or scope.get('session_id')):
        raise TaskError('Review needs an exact receiver and recorded execution owner.')
    if scope.get('kind') not in {'run','turn'} or not (scope.get('run_id') or scope.get('turn_id') or scope.get('run_start_ns')):
        raise TaskError('Choose an exact recorded run or turn before drafting continuity.')
    if (projection.get('window') or {}).get('capture_revision') is False or 'Metadata-only capture' in (projection.get('window') or {}).get('reasons',[]):
        raise TaskError('Metadata-only evidence cannot supply Git or a continuity draft.')
    rows=[projection[key] for key in ('request','agent_update') if isinstance(projection.get(key),dict)]
    for key in ('checks','edits','errors','context_events'):rows.extend(projection.get(key) or [])
    members=(projection.get('usage') or {}).get('step_trace_ids') or []
    for row in rows:
        reference=row.get('source') or {}
        if not isinstance(reference,dict):raise TaskError('Source references must be JSON objects.')
        if any(reference.get(field) and reference[field]!=scope.get(target) for field,target in
            (('service','producer'),('agent_id','agent_id'),('session_id','session_id'))):
            raise TaskError('A source reference contradicts this frozen execution owner.')
        trace=reference.get('trace_id');turn=reference.get('turn_id')
        if turn and turn!=scope.get('turn_id'):raise TaskError('A source reference contradicts this recorded turn.')
        if trace and (trace not in members if scope.get('turn_id') else scope.get('run_id') and trace!=scope['run_id']):
            raise TaskError('A source reference is outside this frozen execution membership.')
    return {key:scope.get(key) for key in SCOPE_FIELDS}


def bind_workspace(projection,workspace,*,reported_workspace=''):
    scope=source_scope(projection)
    if not isinstance(workspace,str) or not workspace.strip():
        raise TaskError('Explicitly choose the local checkout to map to this recorded execution.')
    path=Path(workspace).expanduser().resolve()
    if not path.is_dir():raise TaskError('The explicitly chosen local workspace is unavailable.')
    return dict(kind='explicit-user-mapping',workspace=str(path),reported_workspace=display_text(reported_workspace)[:4096],
        scope=scope,selected_ns=time.time_ns(),
        basis='User explicitly mapped this execution to a local checkout; receiver address and recorded cwd alone are not proof.')


def _safe_git(snapshot):
    result=deepcopy(snapshot);changed=False
    # Whole-block redaction must precede line-level quoted-key treatment, so
    # multiline credentials such as PEM keys cannot be split past the detector.
    for key in ('diff','stat','error'):
        if not isinstance(result.get(key),str):continue
        original=result[key];block=_safe_text(original);changed=changed or block!=original
        lines=[]
        for line in block.splitlines(keepends=True):
            text='[redacted credential-bearing Git line]\n' if any(credential_key(hit.group(1))
                for pattern in QUOTED_FIELDS for hit in pattern.finditer(line)) else line
            changed=changed or text!=line;lines.append(text)
        result[key]=''.join(lines)
    # Fingerprints cover only sanitized fields. Ambiguous/redacted metadata
    # cannot prove equivalence, even when the diff body was harmless.
    for key in ('repo_root','base_commit','head','branch','files','workspace'):
        if key in result:
            if key=='files' and isinstance(result[key],list):
                values=[safe_value(entry) for entry in result[key][:100]]
                complete=len(result[key])<=100 and all(ok for _,ok in values);value=[entry for entry,_ in values]
            else:value,complete=safe_value(result[key])
            changed=changed or not complete;result[key]=value
    result.pop('fingerprint',None)
    if changed:
        result['complete']=False;result.setdefault('warnings',[]).append('Credential material was redacted or metadata was clipped; content equivalence is unavailable.')
    if result.get('complete'):
        material={key:result.get(key) for key in ('repo_root','base_commit','head','branch','files','diff')}
        result['fingerprint']=hashlib.sha256(json.dumps(material,ensure_ascii=False,sort_keys=True).encode()).hexdigest()
    return result


def capture_review_workspace(projection,binding,previous=None):
    scope=source_scope(projection)
    if not isinstance(binding,dict) or binding.get('kind')!='explicit-user-mapping' or binding.get('scope')!=scope:
        raise TaskError('Workspace mapping does not belong to this exact recorded execution.')
    workspace=binding.get('workspace')
    # The saved base follows only this same explicit mapping and source scope.
    old=(previous or {}).get('snapshot') if (previous or {}).get('binding',{}).get('scope')==scope and (previous or {}).get('binding',{}).get('workspace')==workspace else None
    snapshot=_safe_git(capture_workspace(workspace,old))
    return dict(format='agenturm-review-workspace-v1',binding=deepcopy(binding),snapshot=snapshot,
        relation='Current local Git observation; pre-existing, concurrent and committed work may be included. Recorded edits are not a worktree attribution.',
        check_relation='Earlier recorded checks do not validate this Git observation. Historical branch membership is not inferred from current HEAD.')


def freeze_workspace(projection,observation):
    scope=source_scope(projection)
    if not isinstance(observation,dict) or (observation.get('binding') or {}).get('scope')!=scope:
        raise TaskError('Git observation does not belong to this Review scope.')
    frozen=deepcopy(projection);frozen['workspace_observation']=deepcopy(observation)
    return frozen


def editable_draft(projection,task=None):
    scope=source_scope(projection);task=task or {}
    request=projection.get('request') or {};lines=['CONTINUITY DRAFT · review and edit before approving',
        'Captured observations are not independent verification. Your accepted/rejected decisions remain human-authored.', '',
        'ORIGINAL REQUEST',request.get('text') or 'No initiating request was captured in this evidence window.','',
        'RECORDED MODIFYING OPERATIONS']
    edits=projection.get('edits') or []
    lines.extend(str(row.get('action') or 'change')+' · '+str(row.get('path') or 'Path not reported')+
        (' · attempt; effect unknown' if row.get('effect')=='attempt; effect unknown' else '') for row in edits[:40])
    if not edits:lines.append('No modifying operations captured in the loaded interval.')
    lines+=['','RECORDED CHECKS']
    for row in (projection.get('checks') or [])[:20]:
        lines.append(str(row.get('command') or '')+' · '+str(row.get('result') or 'unknown')+
            (' · later recorded edits exist' if row.get('later_edit_count') else ' · current worktree verification unknown'))
    if not projection.get('checks'):lines.append('No recognized checks captured; this does not establish that none ran.')
    lines+=['','RECORDED FAILURES']
    for row in (projection.get('errors') or [])[:10]:
        lines.extend([str(row.get('subject') or 'Recorded failure'),str(row.get('detail') or '')[:500]])
    if not projection.get('errors'):lines.append('None in the loaded evidence; recovery is not inferred from completion.')
    observation=projection.get('workspace_observation') or {};snapshot=observation.get('snapshot') or {}
    lines+=['','CURRENT GIT OBSERVATION']
    if observation:
        lines.extend([snapshot.get('workspace') or 'Workspace not reported',
            'Branch: '+str(snapshot.get('branch') or 'Unknown')+' · HEAD: '+str(snapshot.get('head') or 'Unknown'),
            'Observed at ns: '+str(snapshot.get('captured_ns') or 'Unknown')+' · Base: '+str(snapshot.get('base_commit') or 'Unknown'),
            observation.get('relation',''),observation.get('check_relation','')])
        lines.extend(str(row.get('status') or '')+' '+str(row.get('path') or '') for row in (snapshot.get('files') or [])[:40])
        if snapshot.get('error'):lines.append('Capture issue: '+snapshot['error'])
        if not snapshot.get('complete'):lines.append('Git capture is partial; consult its frozen receipt for limits.')
    else:lines.append('No local checkout has been explicitly mapped and captured for this Review.')
    replaced={row.get('supersedes_id') for row in task.get('decisions',[])}
    lines+=['','CURRENT HUMAN DECISIONS']
    decisions=[row for row in task.get('decisions',[]) if row.get('id') not in replaced]
    lines.extend(str(row.get('kind') or 'decision').upper()+': '+str(row.get('text') or '') for row in decisions[:20])
    if not decisions:lines.append('No accepted or rejected decisions have been entered. Agent claims are not decisions.')
    if projection.get('parallel_path_observations'):
        lines+=['',render_parallel(projection['parallel_path_observations'])]
    lines+=['','NEXT STEP · enter or edit your intended next action before approval','']
    text='\n'.join(str(value) for value in lines)
    if len(text)>30000:text=text[:29700]+'\n[Draft excerpt clipped; the frozen source references remain attached.]'
    return dict(format=DRAFT_FORMAT,created_ns=time.time_ns(),scope=scope,review=deepcopy(projection),
        task_id=task.get('id'),task_revision=task.get('revision'),title=str(projection.get('title') or 'Continue recorded work')[:200],
        text=display_text(text),approval='Unapproved editable draft; nothing has been saved to a task.',
        authored_fields='Existing task title, notes, brief, and immutable decisions are preserved.')


def validate_draft(draft):
    if not isinstance(draft,dict) or draft.get('format')!=DRAFT_FORMAT:raise TaskError('Choose an Agenturm continuity draft.')
    scope=source_scope(draft.get('review'))
    if draft.get('scope')!=scope:raise TaskError('Draft and frozen Review ownership disagree.')
    _text(draft.get('text'),'Reviewed draft',32000,multiline=True)
    if len(json.dumps(draft,ensure_ascii=False).encode())>3*1024*1024:raise TaskError('Continuity draft exceeds the 3 MiB limit.')
    return deepcopy(draft)


def modifying_paths(row):
    if row.get('effect')=='attempt; effect unknown' or str(row.get('result') or '').casefold() in {'error','failed','denied','blocked'}:return set()
    if row.get('action')=='rename':
        before=row.get('from_path');after=row.get('to_path') or row.get('path')
        if not isinstance(before,str) or not isinstance(after,str) or not before or not after or before==after:return set()
    paths=[]
    for key in ('path','from_path','to_path'):
        value=row.get(key)
        if isinstance(value,str) and value.strip() and len(value)<=4096:paths.append(value)
    return set(paths)


def overlap_observations(projections):
    """Bounded observations in explicit mappings, never collision proof.

    At most 20 executions, 40 edits and 20 checks per execution, 200 source
    pairs and 100 observations are considered. Clipping is always disclosed.
    """
    source=list(projections) if isinstance(projections,(list,tuple)) else []
    partial=len(source)>20;result=[];pairs=0;prepared=[]
    for item in source[:20]:
        try:prepared.append((item,source_scope(item)))
        except (ValueError,TypeError,KeyError):partial=True
    def emit(value):
        if len(result)<100:result.append(value)
    def branches(a,b):
        valid=lambda value:value if isinstance(value,str) and value.strip() and len(value)<=4096 else None
        first=valid(a.get('recorded_branch'));second=valid(b.get('recorded_branch'))
        if first and second and first!=second:return None
        workspace=a.get('recorded_workspace')
        return 'same source-recorded workspace and branch' if first and first==second and workspace and workspace==b.get('recorded_workspace') else 'historical branch/workspace unverified'
    def stamp(row):
        value=(row.get('source') or {}).get('time_unix_nano')
        return value if type(value) is int and value>0 else None
    for index,(left,left_scope) in enumerate(prepared):
        for right,right_scope in prepared[index+1:]:
            pairs+=1
            if pairs>200 or len(result)>=100:partial=True;break
            if left_scope['receiver']!=right_scope['receiver'] or not left_scope['agent_id'] or not right_scope['agent_id'] or left_scope['agent_id']==right_scope['agent_id']:continue
            a=left.get('workspace_observation') or {};b=right.get('workspace_observation') or {}
            first=a.get('binding') or {};second=b.get('binding') or {}
            if first.get('kind')!='explicit-user-mapping' or second.get('kind')!='explicit-user-mapping' or first.get('scope')!=left_scope or second.get('scope')!=right_scope:continue
            root_a=(a.get('snapshot') or {}).get('repo_root');root_b=(b.get('snapshot') or {}).get('repo_root')
            if not root_a or root_a!=root_b or not first.get('workspace') or first.get('workspace')!=second.get('workspace'):continue
            edits_a=left.get('edits') or [];edits_b=right.get('edits') or []
            partial=partial or len(edits_a)>40 or len(edits_b)>40 or any(row.get('action')=='rename' and not modifying_paths(row) for row in [*edits_a[:40],*edits_b[:40]])
            for one in edits_a[:40]:
                for two in edits_b[:40]:
                    basis=branches(one,two);common=modifying_paths(one)&modifying_paths(two)
                    if basis is not None and common:
                        emit(dict(paths=sorted(common),sources=[one.get('source'),two.get('source')],agents=[left_scope['agent_id'],right_scope['agent_id']],
                            branch_basis=basis,observation='Recorded modifying-path overlap in an explicitly mapped workspace; effects/conflicts are not independently verified.'))
                    if len(result)>=100:partial=True;break
                if len(result)>=100:break
            # Check/edit chronology is symmetric with respect to input ordering.
            for checker,modifier in ((left,right),(right,left)):
                checks=checker.get('checks') or [];edits=modifier.get('edits') or []
                partial=partial or len(checks)>20 or len(edits)>40
                for check in checks[:20]:
                    completed=check.get('completed_ns')
                    if type(completed) is not int or completed<=0 or check.get('result') not in {'passed','failed'}:continue
                    for edit in edits[:40]:
                        later=stamp(edit);basis=branches(check,edit)
                        if basis is not None and later and later>completed and modifying_paths(edit):
                            emit(dict(paths=sorted(modifying_paths(edit)),sources=[check.get('source'),edit.get('source')],
                                agents=[checker['scope']['agent_id'],modifier['scope']['agent_id']],branch_basis=basis,
                                observation='A recorded check precedes another agent’s recorded modification; it does not validate the later state.'))
                        if len(result)>=100:partial=True;break
                    if len(result)>=100:break
    return dict(observations=result,partial=partial,limits=dict(executions=20,edits_per_execution=40,checks_per_execution=20,execution_pairs=200,observations=100),
        note='Only recorded paths with explicit shared local mapping are compared. Relative/absolute path equivalence and missing rename pairs are not inferred.')



def comparison_projection(projection):
    """Retain only bounded metadata needed for deliberate peer comparisons."""
    source_scope(projection)
    result={key:deepcopy(projection.get(key)) for key in ('format','scope','usage','window','captured_at','title','reported_outcome')}
    result.update(request=None,agent_update=None,errors=[],context_events=[],unclassified_commands=[],checks=deepcopy((projection.get('checks') or [])[:20]),
        edits=deepcopy((projection.get('edits') or [])[:40]))
    observation=projection.get('workspace_observation') or {};snapshot=observation.get('snapshot') or {}
    result['workspace_observation']=dict(binding=deepcopy(observation.get('binding') or {}),snapshot={key:snapshot.get(key)
        for key in ('repo_root','workspace','branch','head','base_commit','captured_ns','complete')})
    if len(json.dumps(result,ensure_ascii=False).encode())>128000:raise TaskError('Peer comparison metadata exceeds its bounded cache budget.')
    return result


def remember_comparison(cache,projection):
    """Eight explicit captures, at most 512 KiB, with no retained Git diffs."""
    value=comparison_projection(projection);scope=source_scope(value)
    key=json.dumps(scope,sort_keys=True)
    cache.pop(key,None);cache[key]=value
    while len(cache)>8 or sum(len(json.dumps(row,ensure_ascii=False).encode()) for row in cache.values())>512000:
        cache.pop(next(iter(cache)))
    return key


def render_parallel(observations):
    rows=observations.get('observations') or []
    lines=['RECORDED PARALLEL-WORK OBSERVATIONS','Explicitly mapped checkouts only. Current Git HEAD is not historical branch proof.']
    for row in rows[:20]:lines.extend([row['observation'],'Paths: '+', '.join(row['paths'])+' · '+row['branch_basis']])
    if not rows:lines.append('No overlap was found in the bounded explicitly captured comparison set; this does not establish absence of conflicts.')
    if observations.get('partial'):lines.append('Comparison clipped to its disclosed execution/event budgets.')
    return '\n'.join(lines)

def render_workspace(observation):
    snapshot=observation.get('snapshot') or {}
    return '\n'.join(['FROZEN LOCAL GIT OBSERVATION',
        'Explicit checkout: '+str((observation.get('binding') or {}).get('workspace') or 'Unknown'),
        'Observed ns: '+str(snapshot.get('captured_ns') or 'Unknown'),
        'Branch: '+str(snapshot.get('branch') or 'Unknown')+' · HEAD: '+str(snapshot.get('head') or 'Unknown'),
        'Base: '+str(snapshot.get('base_commit') or 'Unknown'),observation.get('relation',''),observation.get('check_relation',''),
        'Capture: '+('within output limits' if snapshot.get('complete') else 'partial or unavailable'),
        snapshot.get('error') or '',snapshot.get('stat') or '',snapshot.get('diff') or '',
        *snapshot.get('warnings',[])])


def policy_checker(api,projection):
    """Revalidate a frozen source against its receiver without endpoint guessing."""
    from types import SimpleNamespace
    from .review_facts import review_capture_policy
    from .workflow_evidence import ExecutionScope
    source_scope(projection)
    scope=ExecutionScope(**projection['scope'])
    def check():
        health=api.get('/api/health')
        if not isinstance(health,dict):raise TaskError('Receiver health did not contain a readable policy object.')
        if health.get('receiver_id')!=scope.receiver:raise TaskError('Receiver namespace changed; reopen the recorded execution.')
        snapshot=SimpleNamespace(receiver_id=scope.receiver,local_status=health.get('local_agents') or {})
        if review_capture_policy({},snapshot,scope).get('capture_content') is False:
            raise TaskError('Source capture is metadata-only or revoked; no derived draft or Git content was published.')
        return True
    return check


def draft_formats(draft):
    from .work_receipts import document_html
    from .saved_tasks import _fence
    draft=validate_draft(draft)
    markdown='# Editable continuity draft\n\nNothing has been saved to a task. Review/edit the draft, then explicitly approve it.\n\n'+_fence(draft['text'])+'\n\n## Frozen source scope\n\n'+_fence(json.dumps(draft['scope'],ensure_ascii=False,indent=2))+'\n'
    return dict(markdown=markdown,html=document_html(markdown,'Agenturm continuity draft'),json=json.dumps(draft,ensure_ascii=False,indent=2)+'\n')
