"""Readable projections of captured messages; the original record is never edited.

Only complete, leading runtime context envelopes are separated. Arbitrary XML,
code fences and text discussing an envelope are user content, not scaffolding.
"""
from __future__ import annotations

import json
import re
import unicodedata
from dataclasses import dataclass

_ANSI = re.compile(r'\x1b\[[0-?]*[ -/]*[@-~]|\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)')
_CONTEXT = re.compile(
    r'^<(?P<tag>environment_context|environment_details|skills_instructions|'
    r'user_instructions|developer_instructions|system_instructions|'
    r'system-reminder|INSTRUCTIONS|skill|local-command-caveat|'
    r'local-command-stdout|local-command-stderr)\b[^>]*>.*?</(?P=tag)>', re.S)
_COMMAND_BLOCK = re.compile(r'<(?P<tag>command-name|command-message|command-args)>.*?</(?P=tag)>', re.S)
_LOCAL_CONTROL_NAMES = {'model', 'effort', 'compact', 'clear', 'resume', 'help', 'status',
                        'cost', 'context', 'config', 'theme', 'permissions', 'login',
                        'logout', 'doctor', 'terminal-setup', 'exit', 'quit'}
_TRUNCATED_LOCAL_CAVEAT = re.compile(
    r'^<local-command-caveat>\s*(?:Caveat:\s*)?(?:'
    r'The command below was run directly in Claude Code\b|'
    r'The messages below were generated by the user while running local commands\b)', re.I)
_AGENTS = re.compile(r'^# AGENTS\.md instructions for [^\n]+\n\s*(?=<INSTRUCTIONS>)')
_STEERING = {'yes', 'no', 'ok', 'okay', 'thanks', 'thank you', 'go ahead',
             'continue', 'please continue', 'proceed', 'do it', 'sure', 'sounds good',
             'hi', 'hello', 'hey', 'yes please', 'thanks please continue',
             'merge it', 'force merge all', 'commit it', 'commit and push',
             'use a different model', 'switch to a different model'}
# Match complete operational instructions, never mentions inside a real task.
_MODEL = r'(?:gpt[\w./:+-]*|claude[\w./:+-]*|gemini[\w./:+-]*|o[134][\w./:+-]*|qwen[\w./:+-]*|llama[\w./:+-]*|deepseek[\w./:+-]*|auto|default)'
_CONTROLS = re.compile(
    r'^(?:(?:please|(?:can|could|would)\s+you)\s+)?(?:'
    r'(?:switch|change)(?:\s+(?:the|your))?\s+model(?:\s+to\s+[\w./:@+-]+|\s+' + _MODEL + r')?'
    r'|(?:switch|change)\s+(?:back\s+)?to\s+' + _MODEL + r'(?:\s+model)?'
    r'|(?:use|try)\s+(?:the\s+)?' + _MODEL + r'(?:\s+(?:model|instead))?'
    r'|(?:set|change|switch)(?:\s+the)?\s+(?:reasoning\s+)?effort(?:\s+to)?\s+(?:none|minimal|low|medium|high|xhigh|max|ultra)'
    r'|/(?:model|effort)(?:\s+[\w./:@+-]+)?|/(?:compact|clear|resume)'
    r')(?:\s+please)?$', re.I)
_MISSING = {'task not reported', 'user message', 'assistant message', 'user prompt'}


def message_text(value, depth=0):
    """Unwrap recorded text blocks without flattening their line breaks."""
    if depth > 12:
        return ''
    if isinstance(value, str):
        # A captured string can itself be JSON instructions. Parsing it would
        # lose fields and make the "original" view an inaccurate reconstruction.
        text = _ANSI.sub('', value).replace('\r\n', '\n').replace('\r', '\n')
        return ''.join(c for c in text if c in '\n\t' or unicodedata.category(c) not in {'Cc','Cf'})
    if isinstance(value, dict):
        if (value.get('type') in {'text','input_text','output_text'} or
                set(value)<= {'role','content','text','message','prompt','recorded_content'}):
            for key in ('text', 'content', 'message', 'prompt', 'recorded_content'):
                if key in value:
                    text = message_text(value[key], depth + 1)
                    if text:
                        return text
        return message_text(json.dumps(value,ensure_ascii=False,indent=2),depth+1)
    elif isinstance(value, list):
        return '\n'.join(text for child in value if isinstance(child, (str, dict))
                         if (text := message_text(child, depth + 1)))
    return ''


@dataclass(frozen=True)
class RequestText:
    raw: str
    body: str
    context: tuple[str, ...]


def request_text(value):
    raw = message_text(value)
    remaining = raw.lstrip()
    context = []
    while remaining:
        header = _AGENTS.match(remaining)
        candidate = remaining[header.end():] if header else remaining
        match = _CONTEXT.match(candidate)
        if not match:
            break
        context.append('Repository instructions' if header else
                       match['tag'].replace('_', ' ').replace('-', ' ').capitalize())
        remaining = candidate[match.end():].lstrip()
    return RequestText(raw=raw, body=remaining if context else raw, context=tuple(context))


def request_title(value):
    parsed = request_text(value)
    first = next((line.strip() for line in parsed.body.splitlines() if line.strip()), '')
    if not first:
        return 'Runtime context' if parsed.context else 'Request text unavailable'
    if first.startswith(('<send_user_message_question_reply>', '[{"questionItemId"', '{"questionItemId"')):
        return 'Reply to input request'
    return re.sub(r'^#{1,6}\s+', '', first)


def _after_local_control(body):
    """Consume exactly one complete known operational command envelope."""
    remaining=body.lstrip()
    commands=[]
    while (block := _COMMAND_BLOCK.match(remaining)):
        if block['tag']=='command-name':
            commands.append(block[0].split('>',1)[1].rsplit('<',1)[0].strip().removeprefix('/'))
        remaining=remaining[block.end():].lstrip()
    return remaining if len(commands)==1 and commands[0] in _LOCAL_CONTROL_NAMES else None


def local_command_only(value):
    """Claude local UI records cannot start/resolve a model turn or input wait.

    Only complete known envelopes qualify. Real prose, custom commands, replies,
    and mixed wrapper/request records remain actual user turns.
    """
    remaining=message_text(value).lstrip()
    seen=False
    while remaining:
        match=_CONTEXT.match(remaining)
        if match and match['tag'].startswith('local-command-'):
            remaining=remaining[match.end():].lstrip()
        else:
            tail=_after_local_control(remaining)
            if tail is None:return False
            remaining=tail
        seen=True
    return seen


def task_description(value):
    """First substantive request line, excluding standalone session controls.

    This changes only identity labels. Every original request stays inspectable.
    A control followed by an actual task on another line still yields that task.
    """
    body = request_text(value).body
    # Claude emits these blocks in different orders. Match the whole envelope,
    # never a mention embedded in a real request or a custom task command.
    while body:
        # Old collectors may have saved only a prefix of a runtime envelope as
        # identity. Suppress that label too; raw prompts stay intact.
        if _TRUNCATED_LOCAL_CAVEAT.match(body.lstrip()):
            return ''
        remaining = _after_local_control(body)
        if remaining is None:
            break
        # A local command's stdout/caveat may follow the command in this same
        # record, including multiline output. Keep projecting complete envelopes.
        body = request_text(remaining).body
    if request_title(body) == 'Reply to input request':
        return ''
    for line in body.splitlines():
        if not line.strip():
            continue
        title = request_title(line)
        folded = title.casefold().strip(' .!?')
        if folded in _STEERING | _MISSING | {
                'runtime context', 'request text unavailable', 'reply to input request'}:
            continue
        if _CONTROLS.fullmatch(folded.replace('`', '')):
            continue
        return title
    return ''


def remember_task(session, text):
    """Keep session identity stable; per-turn requests retain their own intent."""
    if not session.capture_details:
        return
    from .local_activity import safe
    if isinstance(text,list):
        text=[block for block in text if isinstance(block,dict)
              and block.get('type') in {'text','input_text','output_text'}]
    # Classify before capture truncation: a large context prefix may otherwise
    # consume the entire record and conceal the actual request at its end.
    parsed = request_text(text)
    description = task_description(parsed.body)
    if description:
        if not session.task_description:
            session.task_description = safe(description,500)
        session.tasks[session.turn] = safe(parsed.body,4000)
